const LANGS = Object.keys(I18N);
const DEFAULT_LANG = 'zh';
const HTML_LANG = { zh: 'zh-CN', en: 'en', ja: 'ja', ko: 'ko' };

let currentLang = LANGS.includes(localStorage.getItem('zenLang')) ? localStorage.getItem('zenLang') : DEFAULT_LANG;

function t(key, vars = {}) {
    const text = I18N[currentLang][key] ?? I18N[DEFAULT_LANG][key] ?? key;
    return text.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? '');
}
